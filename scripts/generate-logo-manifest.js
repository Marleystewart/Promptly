#!/usr/bin/env node
// Which employer logo files actually exist.
//
// The aggregator used to emit `assets/logos/<slug>.png` for every listing and
// let the browser discover the truth: 73 of 121 paths in the live feed pointed
// at files that are not in the repo, so every page load fired dozens of doomed
// image requests and relied on an error handler to clean up after itself. One
// slug was literally undefined, producing `assets/logos/undefined.png`.
//
// This writes the list at build time so the server can simply not claim a logo
// it does not have, and the initials tile becomes a deliberate choice rather
// than a recovery from a failed request.
//
// Run after adding logo files:  node scripts/generate-logo-manifest.js

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "assets", "logos");
const OUT = path.join(ROOT, "api", "_shared", "logo-manifest.js");

// A handful of employers ship a file whose name does not match the ATS slug the
// aggregator derives. Alias rather than rename, so nothing that already
// references the file by name breaks.
const ALIASES = {
  cat: "caterpillar.png",
  mdlz: "mondelez.png",
  msd: "merck.png",
  mwinternshipprogram: "marshallwace.png",
  synchronyfinancial: "synchrony.png",
};

const files = fs.readdirSync(DIR).filter((f) => /\.(png|jpg|jpeg|svg|webp)$/i.test(f)).sort();

// A second index, keyed by the filename stripped of everything but letters and
// digits. A third of the feed comes from sources with no ATS board slug — every
// custom scraper, USAJOBS, several Phenom employers — so those listings asked
// for assets/logos/undefined.png. Matching on the company name recovers them,
// and stripping punctuation is what lets "Goldman Sachs" find
// "goldman-sachs.png" and "Mayo Clinic" find "mayo-clinic.jpeg".
const normalized = {};
for (const f of files) {
  const key = f.replace(/\.[^.]+$/, "").toLowerCase().replace(/[^a-z0-9]/g, "");
  // First writer wins, so a .png beats a .webp of the same employer purely by
  // sort order rather than by whichever readdir happened to return last.
  if (key && !normalized[key]) normalized[key] = f;
}

const body = `// GENERATED by scripts/generate-logo-manifest.js — do not edit by hand.
//
// The set of employer logo files that actually exist in assets/logos, plus
// aliases for the few whose filename does not match the ATS slug. The
// aggregator consults this so it never emits a path to a file we do not have.

const LOGO_FILES = new Set(${JSON.stringify(files, null, 2)});

const LOGO_ALIASES = ${JSON.stringify(ALIASES, null, 2)};

// filename stripped to letters and digits -> the real filename
const LOGO_BY_NAME = ${JSON.stringify(normalized, null, 2)};

function normalizeKey(value) {
  return String(value || "").toLowerCase().replace(/[^a-z0-9]/g, "");
}

// The logo path for a listing, or "" when we genuinely have no file — in which
// case the client draws the coloured initials tile.
//
// Three attempts, in order of how specific they are: the ATS slug, a curated
// alias for the few files whose name does not match that slug, then the company
// name. The last one matters most — a third of the feed has no slug at all.
function logoPathFor(slug, company) {
  const key = String(slug || "").trim().toLowerCase();
  if (key) {
    if (LOGO_ALIASES[key]) return "assets/logos/" + LOGO_ALIASES[key];
    if (LOGO_FILES.has(key + ".png")) return "assets/logos/" + key + ".png";
    const bySlug = LOGO_BY_NAME[normalizeKey(key)];
    if (bySlug) return "assets/logos/" + bySlug;
  }
  const byName = LOGO_BY_NAME[normalizeKey(company)];
  return byName ? "assets/logos/" + byName : "";
}

module.exports = { LOGO_FILES, LOGO_ALIASES, LOGO_BY_NAME, logoPathFor };
`;

fs.writeFileSync(OUT, body);
console.log(`logo-manifest.js written — ${files.length} files, ${Object.keys(ALIASES).length} aliases.`);
